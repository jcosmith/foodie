/// Spacing and radius scale. Use these instead of literal numbers so screens
/// stay consistent.
abstract final class FoodieSpacing {
  static const double extraSmall = 4;
  static const double small = 8;
  static const double medium = 12;
  static const double large = 16;
  static const double extraLarge = 24;

  /// Horizontal padding of screen content.
  static const double screenGutter = 14;

  static const double cardRadius = 16;
  static const double tileRadius = 12;
  static const double sheetRadius = 24;
}
